#!/usr/bin/env node
'use strict';

// The shared catalog is the only handwritten source of effect IDs, enums and defaults.
// This generator owns only the marked Artifact block; all other Rules bytes survive unchanged.
const fs = require('node:fs');
const path = require('node:path');
const {ARTIFACT_CATALOG_VERSION, ARTIFACT_CATALOG, createDefaultArtifactProjection} = require('../artifact-catalog.js');
const target = path.resolve(__dirname, '..', 'firestore.rules');
const begin = '      // BEGIN GENERATED ARTIFACT SETTINGS RULES';
const end = '      // END GENERATED ARTIFACT SETTINGS RULES';
const quote = value => "'" + value.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const list = values => '[' + values.map(quote).join(', ') + ']';
const item = (name, id) => name + '[' + quote(id) + ']';

function generatedBlock() {
  const entries = ARTIFACT_CATALOG;
  if (ARTIFACT_CATALOG_VERSION !== 1 || entries.length !== 63 || new Set(entries.map(entry => entry.effectId)).size !== 63) {
    throw new Error('Unexpected Artifact catalog; review the storage schema before regenerating Rules.');
  }
  const selected = entries.filter(entry => Array.isArray(entry.values));
  const defaults = createDefaultArtifactProjection().items;
  const enumGroups = new Map();
  for (const entry of selected) {
    const key = JSON.stringify(entry.values);
    if (!enumGroups.has(key)) enumGroups.set(key, {values:entry.values, ids:[]});
    enumGroups.get(key).ids.push(entry.effectId);
  }
  const groups = [];
  for (const group of enumGroups.values()) for (let index=0;index<group.ids.length;index+=6) groups.push({ids:group.ids.slice(index,index+6),values:group.values});
  const fixedIds=entries.filter(entry=>!Array.isArray(entry.values)).map(entry=>entry.effectId);
  const fixedItems='['+fixedIds.map(id=>item('items',id)).join(', ')+']';
  const groupFunctions=groups.map((group,index)=>{
    const names=group.ids.map((_,position)=>'v'+position);
    const enumCondition=group.ids.length<=2 && group.values.length>1
      ? names.map(name=>name+'.selectedValue.matches('+quote('^(?:'+group.values.map(value=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('|')+')$')+')').join(' && ')
      : '['+names.map(name=>name+'.selectedValue').join(', ')+'].hasOnly('+list(group.values)+')';
    return '        function artifactCatalogGroup'+index+'('+names.join(', ')+') {\n'
      +(names.length===1 ? '          return '+names[0]+'.size() == 2\n            && '+names[0]+'.needed is bool'
        : '          return ['+names.map(name=>name+'.size()').join(', ')+'].hasOnly([2])\n'
          +'            && ['+names.map(name=>name+'.needed').join(', ')+'].hasOnly([true, false])')
      +'\n            && '+enumCondition+';\n        }';
  }).join('\n');
  const validators=groups.map((group,index)=>'            && artifactCatalogGroup'+index+'('+group.ids.map(id=>item('items',id)).join(', ')+')').join('\n');
  function selectedFieldDecision(ids, knownSelected = false) {
    if (ids.length === 1) {
      const diff=item('next',ids[0])+'.diff('+item('previous',ids[0])+').affectedKeys().size() == 1';
      return knownSelected ? diff : '(!affected.hasAny('+list(ids)+') || '+diff+')';
    }
    const middle=Math.ceil(ids.length/2),left=ids.slice(0,middle),right=ids.slice(middle);
    return '(affected.hasAny('+list(left)+') ? '+selectedFieldDecision(left,true)+' : '+selectedFieldDecision(right,knownSelected)+')';
  }
  const fields=selectedFieldDecision(selected.map(entry=>entry.effectId));
  const defaultLines = entries.map(entry => {
    const value = defaults[entry.effectId];
    return '            ' + quote(entry.effectId) + ": {'needed': false" + (Array.isArray(entry.values) ? ", 'selectedValue': " + quote(value.selectedValue) : '') + '}';
  }).join(',\n');
  return `${begin}
      // Generated by scripts/generate-artifact-rules.cjs from artifact-catalog.js.
      // Do not edit repeated IDs, enums or defaults here; regenerate and run --check.
      match /settings/{artifactSettingsId} {
        function artifactDocument() { return artifactSettingsId in ['awakeningGw', 'awakeningHigh']; }
        function artifactOwnsProfile(identity) {
          return request.auth != null && identity.active == true && identity.profileId == profileId
            && identity.deviceId is string
            && get(/databases/$(database)/documents/memberProfiles/$(profileId)).data.status == 'active'
            && get(/databases/$(database)/documents/memberProfiles/$(profileId)/devices/$(identity.deviceId)).data.status == 'active';
        }
        function artifactSafeInteger(value, minimum) {
          return value is int && value >= minimum && value <= 9007199254740991;
        }
${groupFunctions}
        function artifactItems(input) {
          let items = input;
          // Required field accesses cover every catalog ID; exact count excludes unknown IDs.
          // Item sizes plus required typed fields exclude every missing/extra item field.
          return items is map && items.size() == ${entries.length}
            && ${fixedItems}.hasOnly([{'needed': false}, {'needed': true}])
${validators};
        }
        function artifactSingleFieldUpdate(nextInput, previousInput) {
          let next = nextInput;
          let previous = previousInput;
          let affected = next.diff(previous).affectedKeys();
          return previous is map && affected.size() == 1
            // A balanced decision tree visits only the changed selection's field check.
            && ${fields};
        }
        function artifactDefaultItems() {
          return {
${defaultLines}
          };
        }
        function artifactEnvelope(input, deviceId) {
          let data = input;
          // All eight required fields are accessed below or by the selected items branch.
          return data.size() == 8
            && data.schemaVersion is int && data.schemaVersion == 1
            && data.catalogVersion is int && data.catalogVersion == ${ARTIFACT_CATALOG_VERSION}
            && artifactSafeInteger(data.resetEpoch, 0) && artifactSafeInteger(data.revision, 1)
            && data.createdAt is timestamp
            && data.updatedByDeviceId == deviceId;
        }
        function artifactCreate() {
          let data = request.resource.data;
          let identity = get(/databases/$(database)/documents/memberIdentities/$(request.auth.uid)).data;
          return artifactOwnsProfile(identity) && artifactEnvelope(data, identity.deviceId) && data.resetEpoch == 0 && data.revision == 1
            && data.createdAt == request.time && data.updatedAt == request.time
            && artifactItems(data.items);
        }
        function artifactUpdate() {
          let data = request.resource.data;
          let previous = resource.data;
          let identity = get(/databases/$(database)/documents/memberIdentities/$(request.auth.uid)).data;
          return artifactOwnsProfile(identity) && artifactEnvelope(data, identity.deviceId)
            && data.diff(previous).affectedKeys().hasOnly(['items', 'resetEpoch', 'revision', 'updatedAt', 'updatedByDeviceId'])
            && data.revision == previous.revision + 1 && data.updatedAt == request.time
            && (data.resetEpoch == previous.resetEpoch
              ? artifactItems(data.items) && artifactSingleFieldUpdate(data.items, previous.items)
              : data.resetEpoch == previous.resetEpoch + 1 && data.items == artifactDefaultItems());
        }
        allow get: if artifactDocument()
          && artifactOwnsProfile(get(/databases/$(database)/documents/memberIdentities/$(request.auth.uid)).data);
        allow list, delete: if false;
        allow create: if resource == null && artifactDocument() && artifactCreate();
        allow update: if resource != null && artifactDocument() && artifactUpdate();
      }
${end}`;
}

function replaceBlock(source) {
  const newline = source.includes('\r\n') ? '\r\n' : '\n';
  const block = generatedBlock().replace(/\n/g, newline);
  const start = source.indexOf(begin);
  if (start !== -1) {
    const finish = source.indexOf(end, start);
    if (finish === -1 || source.indexOf(begin, start + begin.length) !== -1) throw new Error('Invalid Artifact Rules markers.');
    return source.slice(0, start) + block + source.slice(finish + end.length);
  }
  const anchor = '      match /settings/historyReadState {';
  const history = source.indexOf(anchor);
  if (history === -1) throw new Error('History Rules insertion anchor is missing.');
  const firstBrace = source.indexOf('{', history);
  let depth = 0;
  for (let position = firstBrace; position < source.length; position += 1) {
    if (source[position] === '{') depth += 1;
    if (source[position] === '}' && --depth === 0) {
      return source.slice(0, position + 1) + newline + block + source.slice(position + 1);
    }
  }
  throw new Error('Unclosed History Rules anchor.');
}

if (require.main === module) {
  const source = fs.readFileSync(target, 'utf8');
  const next = replaceBlock(source);
  if (process.argv.includes('--check')) {
    if (source !== next) { process.stderr.write('Artifact Rules are stale. Run node scripts/generate-artifact-rules.cjs\n'); process.exitCode = 1; }
    else process.stdout.write('Artifact Rules match the shared catalog.\n');
  } else if (source !== next) fs.writeFileSync(target, next, 'utf8');
}
module.exports = {generatedBlock, replaceBlock};
